- Две точечные ранки от ядовитых зубов, жгучая боль.
- Быстро распространяющийся плотный отек конечности синюшно-багрового цвета.
- Слабость, тошнота, тахикардия, головокружение, снижение давления.

#### 📐 Правильный алгоритм первой помощи:
1. **Полный покой и иммобилизация:** обездвижить укушенную конечность шиной или косынкой (мышечные сокращения разгоняют яд по лимфотоку).
2. **Обильное теплое питье:** 3–4 литра воды/чая для ускорения выведения токсинов почками.
3. **Антигистаминные препараты:** Супрастин 1 таб / Цетрин 1 таб.
4. **Обезболивание:** Парацетамол 500 мг (избегать аспирина из-за риска кровоточивости).
5. **Транспортировка пострадавшего на носилках** в ближайшую больницу.

#### ❌ КАТЕГОРИЧЕСКИ ЗАПРЕЩЕНО:
- ❌ **НЕ накладывать жгут:** жгут концентрирует протеолитический яд в конечности, что приводит к ишемии, тотальному некрозу и последующей ампутации!
- ❌ **НЕ делать разрезов и насечек:** высокий риск занесения вторичной инфекции и повреждения сухожилий.
- ❌ **НЕ прижигать рану спичками или углями:** яд проникает на глубину до 1 см, прижигание создает только глубокий ожог.
- ❌ **НЕ употреблять алкоголь.**

