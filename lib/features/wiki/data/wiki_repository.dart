# Математическая модель энергозатрат организма

В автономном походе организм работает в режиме повышенного расхода энергии. Ошибки в расчете калорийности ведут к быстрому переутомлению, потере мышечной массы, снижению иммунитета и риску гипотермии.

---

### 1. Базовый метаболизм (BMR)
Для расчета энергии, необходимой для поддержания жизнедеятельности в состоянии покоя, используется клинически верифицированная формула **Миффлина-Сан Жеора**:

$$\\text{BMR} = (10 \\times \\text{Вес (кг)}) + (6.25 \\times 175) - (5 \\times 30) + 5$$

Для участника весом 75 кг базовый метаболизм составляет:
$$\\text{BMR} = 750 + 1093.75 - 150 + 5 = 1698.75 \\approx 1700 \\text{ ккал/сутки}$$

---

### 2. Эквивалентная дистанция (Учет рельефа)
Каждые 100 метров набора высоты с тяжелым рюкзаком по энергозатратам эквивалентны прохождению 1 километра по равнине:

$$\\text{Эквивалентная дистанция (км)} = \\text{Дистанция (км)} + \\left( \\frac{\\text{Набор высоты (м)}}{100} \\right)$$

*Пример:* переход 15 км с набором высоты +800 м эквивалентен:
$$\\text{Эквивалент} = 15 + \\frac{800}{100} = 23 \\text{ км}$$

---

### 3. Коэффициент физической активности (PAL)
Рассчитывается от средней дневной эквивалентной нагрузки:
- **Менее 12 км/день (Легкий трекинг / ПВД):** $\\text{PAL} = 1.8$
- **12 – 20 км/день (Умеренный горно-пеший поход):** $\\text{PAL} = 2.2$
- **Более 20 км/день или режим «Выживание»:** $\\text{PAL} = 2.6$

---

### 4. Терморегуляция и поправка на холод (Cold Bonus)
На обогрев тела в холодное время года организм расходует дополнительную энергию:
