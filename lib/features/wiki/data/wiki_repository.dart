1. Захватить клеща специальным выкручивателем (Tick Twister / клещеверт) или прочной нитью у самого основания хоботка (вплотную к коже).
2. **Плавными вращательными движениями против часовой стрелки выкрутить клеща** (не тянуть резко вверх, чтобы не оторвать головку).
3. Обработать место укуса антисептиком (спирт, йод, хлоргексидин).
4. Клеща поместить в плотно закрытую баночку с влажной ваткой для анализа в лаборатории.

